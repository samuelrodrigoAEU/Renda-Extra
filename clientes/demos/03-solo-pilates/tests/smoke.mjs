// Teste de fumaça da demo 03: capturas por seção (desktop, tablet, celular) + checagens funcionais.
import { chromium } from 'playwright'
import { mkdirSync } from 'node:fs'
const URL = process.env.URL || 'http://localhost:4175/', OUT = process.env.OUT || 'screens', WAIT = Number(process.env.WAIT || 2500)
mkdirSync(OUT, { recursive: true })
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const R = [], ok = (n, c) => R.push(`${c ? 'PASS' : 'FAIL'} ${n}`)
for (const [label, vp] of [['desktop', { width: 1440, height: 900 }], ['tablet', { width: 820, height: 1180 }], ['mobile', { width: 390, height: 844 }]]) {
  const page = await browser.newPage({ viewport: vp })
  const errors = []
  page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto(URL, { waitUntil: 'networkidle' })
  await page.waitForTimeout(1500)
  const shot = (n) => page.screenshot({ path: `${OUT}/${label}-${n}.png` })
  const go = async (sel, n, off = 0) => { await page.evaluate(([s, o]) => scrollTo({ top: document.querySelector(s).getBoundingClientRect().top + scrollY + o, behavior: 'instant' }), [sel, off]); await page.waitForTimeout(WAIT); await shot(n) }
  await shot('1-hero')
  const fit = await page.evaluate(() => { const w = document.querySelector('#word'), b = document.querySelector('.word-box'); return w.getBoundingClientRect().right <= b.getBoundingClientRect().right + 2 })
  ok(`${label}: palavra elástica cabe na largura`, fit)
  const s0 = await page.evaluate(() => getComputedStyle(document.querySelector('#word')).fontStretch)
  await page.evaluate(() => scrollTo({ top: 300, behavior: 'instant' })); await page.waitForTimeout(1200)
  const s1 = await page.evaluate(() => getComputedStyle(document.querySelector('#word')).fontStretch)
  ok(`${label}: palavra estica com o scroll (${s0} → ${s1})`, s0 !== s1)
  await go('#caminhos', '2-caminhos', -20)
  await page.click('.path-list li[data-goal="cond"] .pick'); await page.waitForTimeout(900)
  ok(`${label}: caminho escolhe objetivo no formulário`, await page.isChecked('#book input[name=goal][value=cond]'))
  await go('#molas', '3-molas', -20)
  await page.waitForFunction(() => document.documentElement.classList.contains('ready'), null, { timeout: 30000 }).catch(() => {})
  ok(`${label}: reformer 3D carregado`, await page.evaluate(() => document.documentElement.classList.contains('ready')))
  await page.click('#spring-chips .chip:nth-child(1)')
  ok(`${label}: mola amarela no leitor`, (await page.textContent('#readout')).includes('amarela'))
  await page.evaluate(() => { const r = document.querySelector('#push'); r.value = '0.8'; r.dispatchEvent(new Event('input')) })
  await page.waitForTimeout(WAIT)
  const x = await page.evaluate(() => Number(getComputedStyle(document.querySelector('.springs-stage')).getPropertyValue('--x')))
  ok(`${label}: carrinho anda com a força (x=${x.toFixed(2)})`, x > 0.2)
  await page.click('#spring-chips .chip:nth-child(3)'); await page.waitForTimeout(WAIT)
  const xr = await page.evaluate(() => Number(getComputedStyle(document.querySelector('.springs-stage')).getPropertyValue('--x')))
  ok(`${label}: mola vermelha resiste mais (x=${xr.toFixed(2)} < ${x.toFixed(2)})`, xr < x - 0.1)
  await page.click('#spring-chips .chip:nth-child(1)')
  await shot('3b-molas-empurrando')
  await page.evaluate(() => { const r = document.querySelector('#push'); r.dispatchEvent(new Event('change')) })
  await go('.trust', '4-confianca', -20)
  await go('#unidades', '5-unidades', -20)
  await page.click('[data-unit="alphamall"]'); await page.waitForTimeout(900)
  ok(`${label}: unidade vai para o formulário`, await page.isChecked('#book input[name=unit][value=alphamall]'))
  ok(`${label}: telefone clicável`, (await page.getAttribute('#call a', 'href')) === 'tel:+556234147852')
  await go('#agendar', '6-agendar', -10)
  await page.fill('[name=nome]', '')
  await page.click('.preview button[type=submit]')
  ok(`${label}: validação do formulário`, await page.isVisible('.form-error'))
  await page.fill('[name=nome]', 'Marina')
  await page.click('#o-time label:nth-child(1)'); await page.click('#o-exp label:nth-child(1)')
  await page.evaluate(() => { window.__o = []; window.open = (u) => window.__o.push(u) })
  await page.click('.preview button[type=submit]')
  const u = decodeURIComponent(await page.evaluate(() => window.__o[0] || ''))
  ok(`${label}: WhatsApp com pedido completo`, ['Marina', 'Reabilitação', 'Alphamall', 'manhã', 'nunca fiz'].every((t) => u.includes(t)))
  await shot('6b-agendar-preenchido')
  await go('#duvidas', '7-duvidas', -20)
  ok(`${label}: sem rolagem horizontal`, !(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)))
  ok(`${label}: console limpo (${errors.length})`, errors.length === 0)
  if (errors.length) console.log(errors.slice(0, 5).join('\n'))
  await page.close()
}
const p = await browser.newPage({ viewport: { width: 1280, height: 800 } })
await p.addInitScript(() => { HTMLCanvasElement.prototype.getContext = () => null })
await p.goto(URL, { waitUntil: 'networkidle' })
await p.evaluate(() => document.querySelector('#molas').scrollIntoView()); await p.waitForTimeout(1500)
ok('fallback sem WebGL', await p.evaluate(() => document.documentElement.classList.contains('no-webgl')))
await p.screenshot({ path: `${OUT}/fallback.png` })
const pr = await browser.newPage({ viewport: { width: 1280, height: 800 }, reducedMotion: 'reduce' })
const er = []; pr.on('pageerror', (e) => er.push(e.message))
await pr.goto(URL, { waitUntil: 'networkidle' }); await pr.waitForTimeout(800)
ok('movimento reduzido sem erros', er.length === 0)
await browser.close()
console.log(R.join('\n'))
