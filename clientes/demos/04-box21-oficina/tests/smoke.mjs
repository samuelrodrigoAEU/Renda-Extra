// Teste de fumaça da demo 04: 3 larguras, sem WebGL, movimento reduzido; checagens funcionais.
import { chromium } from 'playwright'
import { mkdirSync } from 'node:fs'
const URL = process.env.URL || 'http://localhost:4176/', OUT = process.env.OUT || 'screens'
mkdirSync(OUT, { recursive: true })
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const R = [], ok = (n, c) => R.push(`${c ? 'PASS' : 'FAIL'} ${n}`)
for (const [label, vp] of [['desktop', { width: 1440, height: 900 }], ['tablet', { width: 820, height: 1180 }], ['mobile', { width: 390, height: 844 }]]) {
  const page = await browser.newPage({ viewport: vp })
  const errors = []
  page.on('console', (m) => m.type() === 'error' && errors.push(m.text())); page.on('pageerror', (e) => errors.push(e.message))
  await page.goto(URL, { waitUntil: 'networkidle' })
  const h1 = await page.locator('h1').boundingBox()
  ok(`${label}: H1 visível sem rolar`, h1 && h1.y + h1.height < vp.height)
  ok(`${label}: abertura não carrega o 3D antes de interação`, !(await page.evaluate(() => !!window.__scene)))
  await page.mouse.move(vp.width / 2, vp.height / 2)
  await page.waitForFunction(() => document.documentElement.classList.contains('live'), null, { timeout: 30000 }).catch(() => {})
  ok(`${label}: 3D entra após interação`, await page.evaluate(() => document.documentElement.classList.contains('live')))
  await page.click('#explode'); await page.waitForTimeout(3000)
  ok(`${label}: vista explodida com 4 etiquetas`, (await page.locator('.labels li.on').count()) === 4 && (await page.getAttribute('#explode', 'aria-pressed')) === 'true')
  await page.screenshot({ path: `${OUT}/${label}-explode.png` })
  await page.click('#explode')
  const bb = await page.locator('#brake').boundingBox()
  await page.mouse.move(bb.x + 8, bb.y + 8); await page.mouse.down(); await page.waitForTimeout(2500)
  const heat = await page.textContent('#brake-note'); await page.mouse.up()
  ok(`${label}: segurar o freio aquece o disco (${heat})`, /[1-9]\d*%/.test(heat))
  if (label !== 'desktop') {
    await page.click('.menu-btn'); ok(`${label}: menu abre`, await page.isVisible('#menu a'))
    await page.click('#menu a[href="#onde"]'); await page.waitForTimeout(600); ok(`${label}: menu fecha ao navegar`, (await page.getAttribute('.menu-btn', 'aria-expanded')) === 'false')
  }
  await page.evaluate(() => document.querySelector('#oficina').scrollIntoView({ behavior: 'instant' })); await page.waitForTimeout(800)
  await page.click('#next'); ok(`${label}: carrossel avança`, (await page.textContent('#carousel .bn')) === 'BMW')
  await page.click('#carousel [data-brand]'); await page.waitForTimeout(800)
  ok(`${label}: marca do carrossel vai para o diagnóstico`, await page.isChecked('#f-brand input[value=bmw]'))
  await page.click('.ticket button[type=submit]')
  ok(`${label}: validação do diagnóstico`, await page.isVisible('.form-error'))
  await page.fill('[name=modelo]', '320i 2019'); await page.click('#f-sym label:nth-child(2)'); await page.click('#f-run label:nth-child(3)'); await page.fill('[name=nome]', 'Rafael')
  ok(`${label}: aviso de guincho aparece`, await page.isVisible('#tow-note'))
  ok(`${label}: ordem de serviço atualiza`, (await page.textContent('#ticket')).includes('BMW 320i 2019'))
  await page.evaluate(() => { window.__o = []; window.open = (u) => window.__o.push(u) })
  await page.click('.ticket button[type=submit]')
  const u = decodeURIComponent(await page.evaluate(() => window.__o[0] || ''))
  ok(`${label}: WhatsApp com pedido completo`, u.startsWith('https://wa.me/5562981322167') && ['Rafael', 'BMW 320i 2019', 'frear', 'guincho'].every((t) => u.includes(t)))
  await page.screenshot({ path: `${OUT}/${label}-diag.png` })
  ok(`${label}: telefone clicável`, (await page.locator('a[href="tel:+556232518789"]').count()) >= 2)
  ok(`${label}: sem rolagem horizontal`, !(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)))
  ok(`${label}: console limpo (${errors.length})`, errors.length === 0)
  if (errors.length) console.log(errors.slice(0, 4).join('\n'))
  await page.close()
}
const p = await browser.newPage({ viewport: { width: 1280, height: 800 } })
await p.addInitScript(() => { HTMLCanvasElement.prototype.getContext = () => null })
await p.goto(URL, { waitUntil: 'networkidle' }); await p.click('#explode'); await p.waitForTimeout(800)
ok('sem WebGL: explodir troca para o render', (await p.getAttribute('.still', 'src')).includes('exploded') && (await p.isHidden('#brake')))
const pr = await browser.newPage({ viewport: { width: 1280, height: 800 }, reducedMotion: 'reduce' }); const er = []; pr.on('pageerror', (e) => er.push(e.message))
await pr.goto(URL, { waitUntil: 'networkidle' }); await pr.mouse.move(400, 400); await pr.waitForTimeout(1500)
ok('movimento reduzido sem erros', er.length === 0)
await browser.close()
console.log(R.join('\n'))
